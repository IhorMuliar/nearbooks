"""The README's generated numbers cannot drift: test counts, deployment hashes and local builds are checked."""
import contextlib, io, json, os, shutil, sys, tempfile, unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "pipeline"))
import readme_facts, verify  # noqa: E402
from common import load_json  # noqa: E402

METRICS = os.path.join(ROOT, "data", "snapshot-2026-10-20", "metrics.json")


class TestReadmeFacts(unittest.TestCase):
    def test_test_counts_match_the_suites(self):
        loader = unittest.TestLoader()
        n = sum(s.countTestCases() for s in loader.discover(os.path.join(ROOT, "tests"), top_level_dir=ROOT))
        self.assertEqual(readme_facts.test_counts()["python"], n)

    def test_a_changed_test_count_makes_the_readme_stale(self):
        m = load_json(METRICS)
        with open(os.path.join(ROOT, "README.md")) as f:
            txt = f.read()
        orig = readme_facts.test_counts
        try:
            readme_facts.test_counts = lambda: dict(orig(), contract=orig()["contract"] + 1)
            stale = [b for b, e, body in verify.generated_blocks(m) if b + "\n" + body + "\n" + e not in txt]
        finally:
            readme_facts.test_counts = orig
        self.assertIn(readme_facts.marker("test-output")[0], stale)
        self.assertIn(readme_facts.marker("summary")[0], stale)

    def test_a_local_build_that_differs_from_the_deployment_is_reported(self):
        tmp = tempfile.mkdtemp()
        try:
            os.makedirs(os.path.join(tmp, "contract", "res"))
            shutil.copy(os.path.join(ROOT, "contract", "deployment.json"), os.path.join(tmp, "contract"))
            with open(os.path.join(tmp, "contract", "res", "nearbooks.wasm"), "wb") as f:
                f.write(b"\0asm not the deployed code")
            orig = readme_facts.ROOT
            readme_facts.ROOT = tmp
            try:
                problems = readme_facts.check_builds()
            finally:
                readme_facts.ROOT = orig
            self.assertEqual(len(problems), 1)
            self.assertIn("contract/res/nearbooks.wasm", problems[0])
        finally:
            shutil.rmtree(tmp)

    def test_placeholder_markers_are_found(self):
        self.assertEqual(verify.placeholders("a\n<!-- ATTEST_OUTPUT -->\nsee RESOLUTION_NOTE and <!--MCP_OUTPUT-->"),
                         ["<!-- ATTEST_OUTPUT -->", "RESOLUTION_NOTE", "<!--MCP_OUTPUT-->"])
        self.assertEqual(verify.placeholders("<!-- findings:begin (generated by `make readme`) -->\nverify-output, OUTPUT, make verify"), [])
        with open(os.path.join(ROOT, "README.md")) as f:
            self.assertEqual(verify.placeholders(f.read()), [], "README.md has unfilled template placeholders")

    def test_check_readme_fails_on_a_leftover_placeholder(self):
        tmp = tempfile.mkdtemp()
        try:
            os.makedirs(os.path.join(tmp, "docs"))
            for doc in verify.DOCS:
                shutil.copy(os.path.join(ROOT, "docs", doc), os.path.join(tmp, "docs"))
            with open(os.path.join(ROOT, "README.md")) as f:
                txt = f.read()
            readme = os.path.join(tmp, "README.md")
            for extra, want_rc in (("", 0), ("\n<!-- DEPLOY_OUTPUT -->\n", 1), ("\nRESOLUTION_NOTE\n", 1)):
                with open(readme, "w") as f:
                    f.write(txt + extra)
                out = io.StringIO()
                with contextlib.redirect_stdout(out):
                    rc = verify.main(["verify.py", METRICS, "--check-readme", readme])
                self.assertEqual(rc, want_rc, out.getvalue())
                if want_rc:
                    self.assertIn("placeholders left unfilled: README.md: " + extra.strip(), out.getvalue())
        finally:
            shutil.rmtree(tmp)

    def test_every_occurrence_of_a_block_is_checked(self):
        m = load_json(METRICS)
        blocks = verify.generated_blocks(m)
        b, e, body = next(x for x in blocks if x[0] == readme_facts.marker("test-output")[0])
        good = b + "\n" + body + "\n" + e
        self.assertNotIn(b, verify.stale_blocks({"a": good, "b": good}, [(b, e, body)]))
        self.assertIn(b, verify.stale_blocks({"a": good, "b": good.replace("OK", "FAILED")}, [(b, e, body)]))
        self.assertIn(b, verify.stale_blocks({"a": "no block here"}, [(b, e, body)]))

    def test_hand_written_hashes_must_be_in_the_records(self):
        known = readme_facts.record_hashes()
        d = load_json(os.path.join(ROOT, "contract", "deployment.json"))
        tx = d["transactions"][0][1]
        ok = f"tx `{tx}`, code `{d['code_sha256']}`, worker {d['worker_sha256'][:8]}\u2026{d['worker_sha256'][-4:]}, code_hash {readme_facts._b58(d['code_sha256'])[:8]}\u2026x"
        self.assertEqual(readme_facts.hash_problems("t", ok.replace("\u2026x", ""), known), [])
        self.assertEqual(len(readme_facts.hash_problems("t", f"tx `{tx[:-1]}A`", known)), 1)
        self.assertEqual(len(readme_facts.hash_problems("t", "worker bbed939a\u20260000", known)), 1)
        self.assertEqual(len(readme_facts.hash_problems("t", "code " + "ab" * 32, known)), 1)
        for path in verify.doc_paths(os.path.join(ROOT, "README.md")):
            with open(path) as f:
                self.assertEqual(readme_facts.hash_problems(path, f.read(), known), [])

    def test_mainnet_deployment_record_is_consistent(self):
        d = load_json(os.path.join(ROOT, "contract", "deployment.json"))
        t = load_json(os.path.join(ROOT, "contract", "deployment-testnet.json"))
        self.assertEqual((d["network"], d["contract"], t["network"]), ("mainnet", "nearbooks.near", "testnet"))
        self.assertTrue(d["worker_url"].endswith(d["worker_sha256"] + ".wasm"))
        self.assertEqual((d["code_sha256"], d["source_commit"], d["worker_sha256"]), (t["code_sha256"], t["source_commit"], t["worker_sha256"]),
                         "mainnet runs the same reproducible build and worker as testnet")
        self.assertEqual(load_json(os.path.join(ROOT, "site", "contract-cache.json"))["contract"], d["contract"])
        with open(os.path.join(ROOT, "contract", "logs", "mainnet-deploy-2026-10-21.log")) as f:
            log = f.read()
        self.assertIn(f"deploy contract/res/nearbooks.wasm sha256 {d['code_sha256']} + new(owner={d['contract']}", log, "the logged deploy used this build")
        self.assertIn(d["worker_url"], log)
        for rel in sorted({r["log"] for r in d["attested_snapshots"] + d["resolutions"]}):
            with open(os.path.join(ROOT, rel)) as f:
                log += f.read()
        self.assertIn(d["keeper"]["function_call_key"], log)
        for _, tx in d["transactions"]:
            self.assertIn(tx, log)

    def test_testnet_deployment_record_is_consistent(self):
        d = load_json(os.path.join(ROOT, "contract", "deployment-testnet.json"))
        self.assertTrue(d["worker_url"].endswith(d["worker_sha256"] + ".wasm"))
        self.assertEqual(load_json(os.path.join(ROOT, "site", "contract-cache-testnet.json"))["contract"], d["contract"])
        with open(os.path.join(ROOT, "contract", "logs", "testnet-keeper.log")) as f:
            log = f.read()
        self.assertIn(f"contract {d['contract']} (code sha256 {d['code_sha256']})", log, "the logged deploy used this build")
        for rel in sorted({r["log"] for r in d["attested_snapshots"] + d["resolutions"]}):
            with open(os.path.join(ROOT, rel)) as f:
                log += f.read()
        self.assertIn(d["keeper"]["function_call_key"], log)
        for _, tx in d["transactions"]:
            self.assertIn(tx, log)
        with open(os.path.join(ROOT, "contract", "Cargo.toml")) as f:
            toml = f.read()
        self.assertIn(f'image_digest = "{d["reproducible_build"]["image_digest"]}"', toml)
        with open(os.path.join(ROOT, "contract", "logs", "testnet-attested.log")) as f:
            old = f.read()
        with open(os.path.join(ROOT, "contract", "logs", "testnet-resolve.log")) as f:
            old += f.read()
        for p in d["previous_deployments"]:
            self.assertIn(f"contract wasm sha256: {p['code_sha256']}", old)
            for _, tx in p["transactions"]:
                self.assertIn(tx, old)

    def _records_in(self, edit_deployment=None, edit_cache=None, network="testnet"):
        """check_records(network) on a copy of the committed records, after edit_*(dict) changed them."""
        dep, cache, _ = readme_facts.RECORDS[network]
        tmp = tempfile.mkdtemp()
        try:
            d = load_json(os.path.join(ROOT, dep))
            c = load_json(os.path.join(ROOT, cache))
            for edit, obj in ((edit_deployment, d), (edit_cache, c)):
                if edit:
                    edit(obj)
            os.makedirs(os.path.join(tmp, "contract", "logs"))
            os.makedirs(os.path.join(tmp, "site"))
            for rel in {r["log"] for r in d["attested_snapshots"] + d["resolutions"]}:
                shutil.copy(os.path.join(ROOT, rel), os.path.join(tmp, rel))
            for rel, obj in ((dep, d), (cache, c)):
                with open(os.path.join(tmp, rel), "w") as f:
                    json.dump(obj, f)
            orig = readme_facts.ROOT
            readme_facts.ROOT = tmp
            try:
                return readme_facts.check_records(network)
            finally:
                readme_facts.ROOT = orig
        finally:
            shutil.rmtree(tmp)

    def test_recorded_outcomes_match_the_run_logs_and_the_cache(self):
        self.assertEqual(readme_facts.check_records(), [])
        d = load_json(os.path.join(ROOT, "contract", "deployment-testnet.json"))
        self.assertEqual({r["status"] for r in d["resolutions"]}, {"confirmed", "refuted", "void"}, "all three outcomes are recorded on testnet")
        self.assertEqual(self._records_in(), [])
        self.assertEqual(self._records_in(network="mainnet"), [])

    def test_a_wrong_recorded_status_is_reported(self):
        def flip(d):
            next(r for r in d["resolutions"] if r["id"] == 6)["status"] = "refuted"
        problems = self._records_in(edit_deployment=flip)
        self.assertTrue(any("prediction 6" in p and "logs status ['void']" in p for p in problems), problems)
        self.assertTrue(any("prediction 6" in p and "site/contract-cache-testnet.json" in p for p in problems), problems)

    def test_a_cache_that_disagrees_with_the_records_is_reported(self):
        def flip(c):
            next(p for p in c["predictions"] if p["id"] == 5)["status"] = "confirmed"
        self.assertTrue(any(p.startswith("prediction 5: site/contract-cache-testnet.json") for p in self._records_in(edit_cache=flip)))

        def decide(c):
            p = next(p for p in c["predictions"] if p["id"] == 0)
            p["status"], p["resolution"] = "confirmed", {"snapshot_date": "2026-12-31", "observed": "1", "resolved_by": "x", "block_height": 1}
        self.assertEqual(self._records_in(edit_cache=decide, network="mainnet"), ["site/contract-cache.json has prediction 0 confirmed, which contract/deployment.json does not record"])

        def other_tx(c):
            next(s for s in c["attested"] if s["date"] == "2026-10-21")["attestation_checks"]["transaction_hash"] = "x"
        self.assertTrue(any(p.startswith("attested snapshot 2026-10-21: site/contract-cache.json has") for p in self._records_in(edit_cache=other_tx, network="mainnet")))

    def test_a_tx_missing_from_the_run_log_is_reported(self):
        def other(d):
            d["resolutions"][0]["tx"] = d["resolutions"][1]["tx"]
        problems = self._records_in(edit_deployment=other)
        self.assertTrue(any("prediction 4" in p and "has no resolve_prediction tx" in p for p in problems), problems)

if __name__ == "__main__":
    unittest.main()
