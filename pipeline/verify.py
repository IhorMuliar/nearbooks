"""Assert the findings against metrics.json. Every tolerance is derived from the data in that file.

    python3 pipeline/verify.py data/snapshot-2026-10-20/metrics.json            # table + exit code
    python3 pipeline/verify.py METRICS --markdown                                # table as Markdown
    python3 pipeline/verify.py METRICS --check-readme README.md                  # README block must equal --markdown

Findings are defined once, here; the README table is generated from this output (see `make readme`).
"""
import json, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import CONFIG, load_json

BEGIN, END = "<!-- findings:begin (generated by `make readme`) -->", "<!-- findings:end -->"


def findings(m):
    out = []
    add = lambda fid, claim, observed, tol, ok, source: out.append(dict(id=fid, claim=claim, observed=observed, tolerance=tol, ok=bool(ok), source=source))
    rec, rev, bb, sup, h, d = m["reconciliation"], m["revenue"], m["buyback"], m["supply"], m["hsp029"]["windows"], m["deflation"]
    ytd_row, d30_row = rec["rows"][0], rec["rows"][1]
    n = m["window"]["days"]

    # F1: revenue rebuilds from raw wallet inflows
    se_pct = rec["daily_residual_sd_usd"] * math.sqrt(n) / rev["defillama_ytd_usd"] * 100
    add("F1a", "Captured revenue rebuilt from raw wallet inflows matches DefiLlama year-to-date",
        f"${ytd_row['onchain']:,.0f} vs ${ytd_row['defillama']:,.0f} ({ytd_row['delta_pct']:+.2f}%)",
        f"+-{2*se_pct:.2f}% (2 standard errors of the {n} daily residuals; sd ${rec['daily_residual_sd_usd']:,.0f}/day)",
        abs(ytd_row["delta_pct"]) <= 2 * se_pct, "FastNear transfers API; DefiLlama fees/near-intents dailyRevenue")
    lags = rec["pearson_by_lag"]; best_other = max(v for k, v in lags.items() if k != "0")
    add("F1b", "Day-level series line up: correlation peaks at lag 0 (no timestamp shift)",
        f"r = {lags['0']:.4f} at lag 0; best other lag in -3..+3: r = {best_other:.4f}",
        f"lag 0 must beat every shifted lag (noise floor {best_other:.2f})", lags["0"] > best_other, "same")

    # F2: buybacks are custody, not a burn
    bb_w = bb["all_wallets"][bb["wallet"]]
    tol = bb["balance_near_rpc"] * 1e-6
    add("F2a", "Buyback wallet balance is fully explained by transfers in minus transfers out (nothing burned from it)",
        f"{bb['balance_near_rpc']:,.0f} NEAR on-chain = {bb['inflow_external_near']:,.0f} external + {bb['inflow_internal_near']:,.0f} internal in - {bb['outflow_near']:,.0f} out (residual {bb_w['balance_residual_near']:+.2f} NEAR)",
        f"+-{tol:.1f} NEAR (1e-6 of balance; covers gas/storage not in transfer rows)", abs(bb_w["balance_residual_near"]) <= tol,
        "archival RPC view_account; FastNear transfers API")
    add("F2b", "Total supply rose in every sampled interval since 1 Jan (no net burn visible)",
        f"{sup['increasing_intervals']}/{sup['intervals']} intervals up; {sup['first_near']:,.0f} -> {sup['last_near']:,.0f} NEAR ({sup['growth_pct']:+.2f}%)",
        "all intervals (no tolerance)", sup["increasing_intervals"] == sup["intervals"], "archival RPC block headers")
    gap = abs(ytd_row["delta_pct"])
    share = bb["share_reached_pct"]
    add("F2c", "DefiLlama labels all captured revenue as buyback, but only part of it ever reached the buyback wallet",
        f"{share:.1f}% of {bb['revenue_near_since_buyback_start']:,.0f} NEAR (since {bb['buyback_start']}) reached it; DefiLlama implies 100%",
        f"share must be below {100-gap:.2f}% (100% minus the revenue measurement gap F1a)", share < 100 - gap,
        "FastNear transfers API; DefiLlama dailyHoldersRevenue + methodology")
    fe = bb["all_wallets"]["fefundsadmin.sputnik-dao.near"]
    add("F2d", "fefundsadmin has spent almost nothing of what it holds",
        f"holds {fe['balance_near']:,.0f} NEAR; outflows {fe['outflow_near']:.2f} NEAR in {fe['outflow_count']} transfers",
        f"outflows must be below {fe['balance_near']*1e-6:.1f} NEAR (the same 1e-6-of-balance rounding scale as F2a)",
        fe["outflow_near"] <= fe["balance_near"] * 1e-6, "FastNear transfers API; archival RPC")

    # F3: HSP-029 method reproduces
    ws = [h[k]["treasury_share_pct"] for k in sorted(h, key=int)]
    spread = max(ws) - min(ws)
    pub = CONFIG["published_claims"]
    add("F3a", "HSP-029's treasury share of supply growth (10.13%) reproduces from RPC",
        f"{', '.join(f'{k}d: {h[k]['treasury_share_pct']:.3f}%' for k in sorted(h, key=int))} vs published {pub['hsp029_treasury_share_pct']}%",
        f"+-{spread:.3f} pp (spread of our own 7/28/92-day windows)", abs(h['92']['treasury_share_pct'] - pub["hsp029_treasury_share_pct"]) <= spread,
        "archival RPC (block header total_supply, treasury.near view_account); HSP-029 text")
    rates = [h[k]["net_issuance_near_per_day"] * 365 / sup["last_near"] * 100 for k in sorted(h, key=int)]
    sp2 = max(rates) - min(rates)
    add("F3b", "HSP-029's realised issuance (2.45%/yr) reproduces",
        f"28d net issuance {d['net_issuance_near_per_day']:,.0f} NEAR/day = {d['annualised_net_issuance_pct']:.3f}%/yr vs published {pub['hsp029_realized_issuance_pct']}%",
        f"+-{sp2:.3f} pp (spread across our windows)", abs(d["annualised_net_issuance_pct"] - pub["hsp029_realized_issuance_pct"]) <= sp2, "archival RPC; HSP-029 text")

    # F4: net-deflation break-even
    lo_price = min(d["price_usd"], d["price_implied_by_transfers"]["min"])
    hi_take = max(d["take_rate_bps_weekly"] + [d["take_rate_bps"]])
    cons = d["net_issuance_near_per_day"] * lo_price / (hi_take / 1e4) / d["volume_usd_per_day_30d"]
    add("F4a", "NEAR is not net-deflationary at today's volume: break-even volume exceeds current volume even under the least favourable price and take rate seen in the last 30 days",
        f"break-even ${d['breakeven_volume_usd_per_day']/1e6:,.0f}M/day = {d['breakeven_over_current_volume']:.1f}x current ${d['volume_usd_per_day_30d']/1e6:,.0f}M/day; conservative bound {cons:.1f}x",
        f"conservative bound uses price ${lo_price:.2f} (lowest of spot and 7d implied) and take {hi_take:.2f} bps (highest weekly); must exceed 1.0x", cons > 1.0,
        "DefiLlama dexs volume; FastNear transfers; archival RPC")
    add("F4b", "At the proposed 1.6% issuance, break-even volume falls but stays above current volume",
        f"${d['breakeven_volume_usd_per_day_at_target']/1e6:,.0f}M/day = {d['breakeven_over_current_volume_at_target']:.1f}x current",
        f"conservative bound {cons*d['net_issuance_at_target_near_per_day']/d['net_issuance_near_per_day']:.1f}x must exceed 1.0x",
        cons * d["net_issuance_at_target_near_per_day"] / d["net_issuance_near_per_day"] > 1.0, "as F4a; target rate from HSP-029")
    pi = d["price_implied_by_transfers"]
    add("F4c", "Spot price used (DefiLlama coins) agrees with the USD valuation FastNear attached to recent transfers",
        f"spot ${d['price_usd']:.2f}; implied by {pi['n']} transfers in last 7d: median ${pi['median']:.2f}, range ${pi['min']:.2f}-${pi['max']:.2f}",
        "spot must lie inside the 7d implied range", pi["min"] <= d["price_usd"] <= pi["max"], "DefiLlama coins API; FastNear transfers API")
    add("F4d", "Our daily sums reproduce DefiLlama's own 30-day revenue field (parsing check)",
        f"${rev['defillama_last30d_usd']:,.0f} vs published total30d ${rev['defillama_total30d_field_usd']:,.0f}", "exact", abs(rev["defillama_last30d_usd"] - rev["defillama_total30d_field_usd"]) < 1, "DefiLlama")
    return out


def table(fs):
    return [f"{'PASS' if f['ok'] else 'FAIL'} {f['id']}  {f['claim']}\n       observed : {f['observed']}\n       tolerance: {f['tolerance']}" for f in fs]


def markdown(fs):
    lines = ["| ID | Finding | Observed | Tolerance (derived from data) | Source | Check |", "|---|---|---|---|---|---|"]
    for f in fs:
        lines.append(f"| {f['id']} | {f['claim']} | {f['observed']} | {f['tolerance']} | {f['source']} | {'PASS' if f['ok'] else 'FAIL'} |")
    return "\n".join(lines)


def main(argv):
    m = load_json(argv[1])
    fs = findings(m)
    if "--markdown" in argv:
        print(markdown(fs)); return 0
    if "--check-readme" in argv:
        with open(argv[argv.index("--check-readme") + 1]) as f:
            txt = f.read()
        want = BEGIN + "\n" + markdown(fs) + "\n" + END
        if want in txt:
            print("README findings block matches the verified output"); return 0
        print("README findings block is stale: run `make readme`"); return 1
    print("\n".join(table(fs)))
    ok = all(f["ok"] for f in fs)
    print(f"\nas_of {m['as_of']}: {sum(f['ok'] for f in fs)}/{len(fs)} findings hold -> " + ("ALL PASS" if ok else "SOME FAILED"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
